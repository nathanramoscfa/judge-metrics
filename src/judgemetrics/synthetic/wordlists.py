# src/judgemetrics/synthetic/wordlists.py
"""Dictionary-word lists every synthetic name is composed from.

The security rule for synthetic data (ROADMAP.md §5 data classification,
docs/DATA_SOURCES.md ``synthetic``) is that person and judge names come from
word lists, never from lists of real people. Given-name tokens are colours,
minerals, and weather words; family-name tokens are trees, birds, and
rivers. Each list holds at least 150 tokens.

By construction no token is a common real given name or surname: words that
double as names (Amber, Hazel, Ruby, Rose, Robin, Martin, Hudson, Jordan,
Willow, Rowan, Jasper, Flint, Salmon, Arno, ...), colours named after people
(Isabelline, Gainsboro), and words that name a people or read as an insult
(Chinook, Osage, Cacique, Drongo, Bustard) were removed when the lists were
written, and the lists are reviewed in the pull request that changes them.
Every token is plain ASCII letters, capitalised, so a composed name
round-trips through ``normalize_person_name`` unchanged apart from case.

The unit test ``test_synthetic_generator.py`` asserts that every name token
in the golden fixture and in a demo run is in these lists.
"""

