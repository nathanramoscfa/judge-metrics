GIVEN_TOKENS: tuple[str, ...] = COLOURS + MINERALS + WEATHER
FAMILY_TOKENS: tuple[str, ...] = TREES + BIRDS + RIVERS

MINIMUM_TOKENS = 150


def compose_name(rng: random.Random) -> tuple[str, str]:
    """One given token and one family token drawn from the lists."""
    return choice(rng, GIVEN_TOKENS), choice(rng, FAMILY_TOKENS)


def full_name(given: str, family: str) -> str:
    return f"{given} {family}"


def is_listed_name(name: str) -> bool:
    """True when ``name`` is exactly one given token and one family token."""
    parts = name.split(" ")
    return len(parts) == 2 and parts[0] in GIVEN_TOKENS and parts[1] in FAMILY_TOKENS
