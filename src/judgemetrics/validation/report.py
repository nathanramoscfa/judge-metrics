# src/judgemetrics/validation/report.py
"""``docs/VALIDATION.md``: the validation of the expected-outcome models, rendered.

``build_report(session, settings, truth_dir=)`` assembles a
``ValidationReport`` from the latest snapshot's fitted models (as the
ingest role: the subgroup calibration reads the restricted schema): per
source, the dataset (register name, coverage window, the frame's row counts,
and — for a synthetic source whose manifest the truth directory holds — the
manifest's seed, scale, generator and truth versions); per model, the
temporal-split diagnostics (Brier score and skill, ROC AUC, calibration in
the large, slope, the ten calibration bins), the observed rate and the mean
prediction per calendar year, and the coefficients' bootstrap stability;
the missing-data sensitivity, the bootstrap stability of the judge-level
estimates, the subgroup calibration, and the recovery of the planted
effects. ``render_report(report)`` turns it into Markdown wrapped at 80
columns. Nothing in it is a UUID, a hash, a judge's name or code, a code
version, a timestamp of a run, or a local path, and every list has an order
the data alone fixes (specification order, vocabulary order, calendar
order), so the same dataset renders the same document in any database.
``check_report`` and ``write_report`` follow ``methodology render``: a
relative path is resolved under the repository root.
"""

