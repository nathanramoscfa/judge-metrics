def render_report(report: ValidationReport) -> str:
    """The Markdown document (LF line endings, one trailing newline, 80 columns)."""
    lines: list[str] = []
    for section in (
        _section_header(report),
        _section_dataset(report),
        _section_summary(report),
        _section_calibration(report),
        _section_temporal(report),
        _section_features(report),
        _section_sensitivity(report),
        _section_bootstrap(report),
        _section_subgroups(report),
        _section_recovery(report),
        _section_limitations(),
    ):
        lines.extend(section)
    return "\n".join(lines).rstrip("\n") + "\n"


def check_report(path: Path, rendered: str) -> list[str]:
    """The unified diff between the file at ``path`` and ``rendered``; empty when equal."""
    try:
        current = path.read_bytes().decode("utf-8")
    except FileNotFoundError:
        return [f"--- {path} is missing", f"+++ render ({len(rendered.splitlines())} lines)"]
    if current == rendered:
        return []
    return list(
        difflib.unified_diff(
            current.splitlines(),
            rendered.splitlines(),
            fromfile=str(path),
            tofile="render",
            lineterm="",
        )
    )


def write_report(path: Path, rendered: str) -> None:
    """Write ``rendered`` to ``path`` (LF, UTF-8), creating parent directories."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(rendered.encode("utf-8"))
