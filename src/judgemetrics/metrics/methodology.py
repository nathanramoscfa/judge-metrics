def _fill(text: str, *, initial: str = "", subsequent: str = "") -> str:
    return textwrap.fill(
        text,
        width=WIDTH,
        initial_indent=initial,
        subsequent_indent=subsequent,
        break_long_words=False,
        break_on_hyphens=False,
    )


def _bullet(text: str) -> str:
    return _fill(text, initial="- ", subsequent="  ")


def _numbered(index: int, text: str) -> str:
    prefix = f"{index}. "
    return _fill(text, initial=prefix, subsequent=" " * len(prefix))


def _attribution_lines(metric: MetricDefinitionSpec) -> Iterable[str]:
    rule = metric.attribution
    parts: list[str] = []
    if rule.decision_type is not None:
        parts.append(f"decision type {rule.decision_type}")
    if rule.actor_types is not None:
        parts.append(f"actor {' or '.join(rule.actor_types)}")
    if rule.discretion is not None:
        parts.append(f"discretion {' or '.join(rule.discretion)}")
    parts.append(f"gate: {GATE_TEXT[rule.assignment_gate]}")
    yield _bullet(f"Attribution: {'; '.join(parts)}.")
    if metric.counted:
        conditions = ", ".join(
            f"{column} = {str(value).lower() if isinstance(value, bool) else value}"
            for column, value in metric.counted
        )
        yield _bullet(f"Counted rows: {conditions}.")


def _metric_section(metric: MetricDefinitionSpec) -> list[str]:
    lines = [f"### {metric.name}", ""]
    lines.append(_bullet(f"Slug: `{metric.slug}` (version {metric.version})."))
    lines.append(
        _bullet(
            f"Kind: {KIND_TEXT[metric.kind]}; unit: {metric.unit}; subjects: "
            f"{', '.join(metric.subject_types)}."
        )
    )
    lines.append(_bullet(f"What it says: {metric.description}"))
    lines.append(_bullet(f"Numerator: {metric.numerator}"))
    lines.append(_bullet(f"Denominator: {metric.denominator}"))
    lines.append(_bullet(f"Eligibility: {metric.eligibility}"))
    lines.extend(_attribution_lines(metric))
    if metric.is_windowed:
        lines.append(
            _bullet(
                f"Index event: {metric.index_event}; outcome: {metric.outcome}; "
                f"windows: {', '.join(str(w) for w in metric.windows_days or ())} days."
            )
        )
    if metric.dimension is not None:
        lines.append(_bullet(f"Dimension: one observation per {metric.dimension} value."))
    if metric.measure is not None:
        lines.append(_bullet(f"Measure: {metric.measure}."))
    lines.append(
        _bullet(
            f"Suppression threshold: {metric.suppression_threshold}"
            + (
                " (never suppressed: a count)."
                if metric.suppression_threshold == 0
                else " (suppressed below this denominator)."
            )
        )
    )
    lines.append("")
    return lines


def render_methodology(registry: Registry | None = None) -> str:
    """The Markdown document (LF line endings, one trailing newline, 80 columns)."""
    registry = registry or load_registry()
    lines: list[str] = [PATH_COMMENT, GENERATED_NOTICE, "# Methodology", ""]
    lines.append(
        _fill(
            f"Registry version {registry.version}; methodology version "
            f"{registry.methodology_version}; {len(registry.metrics)} metrics."
        )
    )
    lines.append("")
    lines.append(
        _fill(
            "This document is rendered from the versioned metric registry "
            "(`data/reference/metric_registry.yaml`), the contract every published "
            "number is computed against. These statistics describe associations in "
            "available records. They do not prove that a judicial decision caused a "
            "later event. There is no composite, ideological, partisan, or "
            "best-or-worst judge score."
        )
    )
    lines.append("")
    lines.extend(["## How to read a number", ""])
    for term, text in HOW_TO_READ:
        lines.append(_bullet(f"**{term}**: {text}"))
    lines.append("")
    lines.extend(["## Index events, exposure, and censoring", ""])
    for term, text in SEMANTICS:
        lines.append(_fill(f"**{term}.** {text}"))
        lines.append("")
    lines.extend(["## Attribution", ""])
    for paragraph in ATTRIBUTION_TEXT:
        lines.append(_fill(paragraph))
        lines.append("")
    lines.extend(["## Metrics", ""])
    lines.append(
        _fill(
            "One section per metric, in registry order. A metric's formula is its "
            "numerator over its denominator; its eligibility states which rows "
            "enter; its attribution rule states how a row is tied to the subject."
        )
    )
    lines.append("")
    for metric in registry.metrics.values():
        lines.extend(_metric_section(metric))
    lines.extend(["## Suppression", ""])
    lines.append(_fill(f"Default threshold: {registry.suppression.default_threshold}."))
    lines.append("")
    lines.append(_fill(registry.suppression.rule))
    lines.append("")
    lines.append(_fill(registry.suppression.rationale))
    lines.append("")
    lines.extend(["## Known limitations", ""])
    lines.append(
        _fill(
            "The brief's statistical warnings, published verbatim and never softened "
            "for presentation:"
        )
    )
    lines.append("")
    for index, warning in enumerate(registry.known_limitations, start=1):
        lines.append(_numbered(index, warning))
    lines.append("")
    lines.extend(["## Methodology changelog", ""])
    for version, text in CHANGELOG:
        lines.append(_bullet(f"{version} - {text}"))
    lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def resolve_output(path: Path) -> Path:
    """An absolute path as given; a relative one under the repository root."""
    return (path if path.is_absolute() else REPO_ROOT / path).resolve()


def check_methodology(path: Path, registry: Registry | None = None) -> list[str]:
    """The unified diff between the file at ``path`` and the render; empty when equal."""
    rendered = render_methodology(registry)
    try:
        current = path.read_bytes().decode("utf-8")
    except FileNotFoundError:
        return [f"--- {path} is missing", f"+++ render ({len(rendered.splitlines())} lines)"]
    if current == rendered:
        return []
    return list(
        difflib.unified_diff(
            current.splitlines(),
            rendered.splitlines(),
            fromfile=str(path),
            tofile="render",
            lineterm="",
        )
    )


def write_methodology(path: Path, registry: Registry | None = None) -> None:
    """Write the render to ``path`` (LF, UTF-8), creating parent directories."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(render_methodology(registry).encode("utf-8"))
