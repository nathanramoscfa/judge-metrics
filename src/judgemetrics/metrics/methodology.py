"""Render ``docs/METHODOLOGY.md`` from the metric registry.

The committed document is a snapshot of ``render_methodology()`` the way
``docs/openapi.json`` is a snapshot of the OpenAPI document:
``judgemetrics methodology render`` writes it, ``--check`` (and the unit
test) fails when the file differs, so a registry change reaches the
methodology page in the same pull request. The text is wrapped at 80
columns; the brief's statistical warnings are rendered verbatim,
unsoftened, as the "Known limitations" list. A relative output path is
resolved under the repository root, never the working directory.
"""

